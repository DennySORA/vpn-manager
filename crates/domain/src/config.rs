/// Where a profile came from.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(tag = "kind", rename_all = "snake_case")]
#[ts(export)]
pub enum ProfileSource {
    /// Imported `WireGuard` configuration (file, paste, CLI).
    Imported,
    /// Generated by a Provider adapter for one account/device/server.
    Provider {
        account_id: ProviderAccountId,
        /// Provider-side device identifier (opaque string, not a UUID).
        device_id: String,
        /// The exit server: where traffic leaves the provider's network.
        server_id: String,
        /// Where the tunnel enters the provider's network when that is not the exit server's
        /// default entry; `None` (every profile before entries could be chosen): there.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        #[ts(optional)]
        entry: Option<ProfileEntry>,
    },
}

/// Where a provider profile's tunnel enters the provider's network, when that is not its exit
/// server's default entry. Display and selection only: the peer (`PeerSpec`) is what connects.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(tag = "kind", rename_all = "snake_case")]
#[ts(export)]
pub enum ProfileEntry {
    /// Mullvad multihop: the tunnel enters at relay `server_id` (its IPv4 address, on the exit
    /// relay's multihop port, with the exit relay's key) and leaves at the exit relay.
    Relay {
        server_id: String,
        /// ISO 3166-1 alpha-2, upper case.
        country_code: Option<String>,
        country: Option<String>,
        city: Option<String>,
    },
    /// `AirVPN`: the exit server's own entry address `index` (0-based, in `AirVPN`'s order: its
    /// "Entry IP 1", shown as 位址 1, is 0) on UDP `port`, one of its `WireGuard` modes. Entry and
    /// exit are the same server.
    Address { index: u8, port: u16 },
}

