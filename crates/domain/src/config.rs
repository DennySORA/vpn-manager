/// Resource limits of one App's process tree; `None` leaves that resource unlimited.
///
/// Which of them a host enforces is in its capabilities (`limit_memory`, `limit_cpu`,
/// `limit_processes`, `limit_open_files`): saving or starting an App with a limit the host cannot
/// enforce is refused.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize, TS)]
#[ts(export)]
pub struct AppLimits {
    /// Memory of the whole tree, MiB (Linux cgroup `memory.max`; swap is not used).
    #[serde(default)]
    pub memory_mib: Option<u32>,
    /// CPU time of the whole tree, percent of one core (Linux cgroup `cpu.max`; 200 = two cores).
    #[serde(default)]
    pub cpu_percent: Option<u32>,
    /// Tasks of the whole tree: processes and each of their threads (Linux cgroup `pids.max`).
    #[serde(default)]
    pub processes: Option<u32>,
    /// Open files, sockets included, of each process on its own (`RLIMIT_NOFILE`).
    #[serde(default)]
    pub open_files: Option<u32>,
}

impl AppLimits {
    /// A limit only a cgroup enforces is set.
    #[must_use]
    pub const fn wants_cgroup(&self) -> bool {
        self.memory_mib.is_some() || self.cpu_percent.is_some() || self.processes.is_some()
    }
}

pub const APP_MEMORY_MIB: std::ops::RangeInclusive<u32> = 16..=1_048_576;
pub const APP_CPU_PERCENT: std::ops::RangeInclusive<u32> = 1..=6_400;
