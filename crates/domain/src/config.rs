/// Where a provider-assigned inbound port came from.
///
/// Manual entries are never "verified"; no provider offers an API that could verify one (`AirVPN`
/// reserves ports in its Client Area, Mullvad removed port forwarding), so the server records every
/// binding as `manual`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "snake_case")]
#[ts(export)]
pub enum AssignmentSource {
    Manual,
    ProviderVerified,
}

/// A port forward: inbound traffic that reaches the connection's tunnel address on `tunnel_port` is
/// connected to a managed App of the same connection, on the loopback port it listens on.
///
/// The provider's assignment (its public port) is folded in: the provider reserves the port on its
/// side, this records where it arrives and where it goes.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[ts(export)]
pub struct ForwardBinding {
    pub id: ForwardBindingId,
    #[serde(flatten)]
    pub meta: EntityMeta,
    pub instance_id: InstanceId,
    pub name: String,
    pub protocol: ForwardProtocol,
    /// Port on the tunnel address that receives inbound traffic (the provider's "local port").
    pub tunnel_port: u16,
    /// Public port at the provider, as the user reserved it (shown; never verified here).
    pub public_port: Option<u16>,
    pub assignment_source: AssignmentSource,
    /// The managed App whose loopback port receives the traffic.
    pub target_app_id: AppId,
    pub target_port: u16,
    pub enabled: bool,
    /// Concurrent inbound TCP connections, and UDP flows, the forward carries.
    #[serde(default = "default_forward_connections")]
    pub max_connections: u32,
    /// Opt-in: every forwarded TCP connection starts with one PROXY protocol v2 header naming the
    /// remote peer as the tunnel saw it and the tunnel address and port it reached, so the App
    /// learns who connected (it otherwise sees every connection come from loopback). The App must
    /// expect the header, or its connections break. TCP only: UDP is relayed as it is, and a
    /// UDP-only forward cannot turn it on. Off for forwards saved before it existed.
    #[serde(default)]
    pub proxy_protocol: bool,
    /// Opt-in, strict connections only: the UDP goes straight into the connection's sandbox, to
    /// the App's own socket on `tunnel_port` (bound on every address or on the tunnel address),
    /// instead of being relayed from loopback. The App then sees every datagram's real source —
    /// what a DHT or Kad needs to route by and answer — and answers from its own port. The worker
    /// neither holds nor relays the port; the sandbox's packet filter lets a remote end in only
    /// while the forward's lease stands and the gate is open, after the same inbound guard and
    /// flow limit. Needs UDP, a strict connection and App, and `target_port == tunnel_port` (no
    /// address translation inside). TCP is unchanged. Off for forwards saved before it existed.
    #[serde(default)]
    pub udp_direct: bool,
}

#[must_use]
pub const fn default_forward_connections() -> u32 {
    256
}

