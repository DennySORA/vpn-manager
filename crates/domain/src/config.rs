/// What kind of program an App runs, as far as starting it as a process of its own goes.
///
/// The executable is recognised by its macOS bundle (`CFBundleIdentifier`) or its file name
/// (`vpn_platform::apps::class`); anything else is an ordinary program (no class).
///
/// A browser started again while the user's own copy runs normally hands the start to that
/// running, unprotected process and exits: the App would silently not be isolated. A data
/// directory of the App's own (inside its private home) makes it a separate browser instead;
/// programs that cannot be made one are refused where VPN Manager would otherwise promise
/// confinement (`enforced_proxy`).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, TS)]
#[serde(rename_all = "snake_case")]
#[ts(export)]
pub enum AppClass {
    /// A Chromium-family browser (Chrome, Chromium, Edge, Brave, Arc, Vivaldi, Opera): started
    /// with `--user-data-dir` in the App's home, never handing over to a running one.
    Chromium,
    /// A Firefox-family browser: `-profile <dir> -no-remote -new-instance` in the App's home.
    Firefox,
    /// A macOS app (Safari, any other bundle) that cannot be made to start as a process of its
    /// own: while it already runs, a start may hand over to that process.
    Gui,
    /// A program whose job is to have another program started (`open`, `xdg-open`): what it
    /// starts is not its child.
    Launcher,
}

/// What an executable was recognised as (see [`AppClass`]).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[ts(export)]
pub struct AppClassInfo {
    pub class: AppClass,
    /// What was recognised, for display: "Google Chrome", "Firefox", "Safari", a bundle's name.
    pub name: String,
    /// macOS: the bundle's `CFBundleIdentifier`.
    pub bundle_id: Option<String>,
}

/// A Chromium-family browser's data directory, inside the App's home.
pub const APP_CHROMIUM_DATA_DIR: &str = "chromium-data";
/// A Firefox-family browser's profile directory, inside the App's home.
pub const APP_FIREFOX_PROFILE_DIR: &str = "firefox-profile";

impl AppClass {
    /// Arguments the launcher puts before the App's own (placeholders not yet replaced): a data
    /// directory of the App's own, so a browser that already runs is never reused.
    #[must_use]
    pub const fn launch_args(self) -> &'static [&'static str] {
        match self {
            Self::Chromium => &["--user-data-dir={app_home}/chromium-data"],
            Self::Firefox => &[
                "-profile",
                "{app_home}/firefox-profile",
                "-no-remote",
                "-new-instance",
            ],
            Self::Gui | Self::Launcher => &[],
        }
    }

    /// The directory [`Self::launch_args`] names, relative to the App's home (created, private,
    /// before every start).
    #[must_use]
    pub const fn data_dir(self) -> Option<&'static str> {
        match self {
            Self::Chromium => Some(APP_CHROMIUM_DATA_DIR),
            Self::Firefox => Some(APP_FIREFOX_PROFILE_DIR),
            Self::Gui | Self::Launcher => None,
        }
    }

    /// The App's own argument `arg` chooses the data directory or profile itself: refused, the
    /// launcher's must stay in force. Chromium reads `--switch=value` with one or two dashes;
    /// Firefox matches `-name`/`--name` case-insensitively and takes `-P` for a named profile of
    /// the user's own profiles.
    #[must_use]
    pub fn selects_profile(self, arg: &str) -> bool {
        match self {
            Self::Chromium => {
                let name = arg
                    .strip_prefix("--")
                    .or_else(|| arg.strip_prefix('-'))
                    .unwrap_or_default();
                let name = name.split_once('=').map_or(name, |(n, _)| n);
                name.eq_ignore_ascii_case("user-data-dir")
            }
            Self::Firefox => {
                let name = arg
                    .strip_prefix("--")
                    .or_else(|| arg.strip_prefix('-'))
                    .unwrap_or_default();
                let name = name.split_once('=').map_or(name, |(n, _)| n);
                ["p", "profile", "profilemanager"]
                    .iter()
                    .any(|n| name.eq_ignore_ascii_case(n))
            }
            Self::Gui | Self::Launcher => false,
        }
    }

    /// A start may hand over to a process VPN Manager did not start (nothing makes this program
    /// a process of its own).
    #[must_use]
    pub const fn may_hand_off(self) -> bool {
        matches!(self, Self::Gui | Self::Launcher)
    }
}

