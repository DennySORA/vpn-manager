/// An IP blocklist. Its ranges are stored apart from this record (control DB table
/// `blocklist_content`), identified by `content_sha256`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[ts(export)]
pub struct Blocklist {
    pub id: BlocklistId,
    #[serde(flatten)]
    pub meta: EntityMeta,
    pub name: String,
    pub source: BlocklistSource,
    pub stats: BlocklistStats,
    /// SHA-256 of the compiled ranges.
    pub content_sha256: String,
    /// When the content last changed (an upload, or a refresh that found new content).
    pub content_updated_at: Timestamp,
    /// The first invalid lines of the current content (at most 50).
    pub invalid_lines: Vec<InvalidLine>,
    /// Key of the built-in catalogue entry this list was created from
    /// (`builtin_blocklists::BUILTIN_BLOCKLISTS`); `None` for a list the user added.
    #[serde(default)]
    pub builtin: Option<String>,
    /// A disabled list is neither downloaded nor enforced anywhere; security profiles keep it
    /// selected for when it is enabled again.
    #[serde(default = "enabled_by_default")]
    pub enabled: bool,
}

const fn enabled_by_default() -> bool {
    true
}

impl Blocklist {
    /// A built-in list whose first download has not happened yet: it enforces nothing. (Only a
    /// built-in list is ever stored without content; anything the user saves has entries.)
    #[must_use]
    pub const fn awaiting_content(&self) -> bool {
        self.builtin.is_some() && self.stats.entries == 0
    }
}

