/// Auto-ban of sources that open too many new inbound connections (port forwards only; nothing else
/// arrives from outside).
///
/// A source that opens more than `threshold` new connections within `window_secs` is banned for
/// `ban_secs`; at most `max_bans` sources are banned at once.
///
/// On by default (the user's decision of 2026-11-02): the default policy of a connection without
/// a security profile uses [`AutoBanSettings::default`], and so does a new security profile.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[ts(export)]
pub struct AutoBanSettings {
    pub enabled: bool,
    pub window_secs: u32,
    pub threshold: u32,
    pub ban_secs: u32,
    pub max_bans: u32,
}

impl Default for AutoBanSettings {
    fn default() -> Self {
        Self {
            enabled: true,
            window_secs: 10,
            threshold: 100,
            ban_secs: 900,
            max_bans: 10_000,
        }
    }
}

/// The auto-ban a connection runs: its security profile's settings, or — without one — the default
/// security policy's ([`AutoBanSettings::default`], on).
///
/// The blocklist side of the same precedence is `blocklist::effective_lists`.
#[must_use]
pub fn effective_auto_ban(security: Option<&SecurityProfile>) -> AutoBanSettings {
    security.map_or_default(|s| s.auto_ban.clone())
}

/// An inclusive range of destination ports (`start..=end`, both 1–65535).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, TS)]
#[ts(export)]
pub struct PortRange {
    pub start: u16,
    pub end: u16,
}

impl PortRange {
    #[must_use]
    pub const fn contains(&self, port: u16) -> bool {
        self.start <= port && port <= self.end
    }
}

/// Destination policy applied by the Instance worker to every payload flow, and the inbound policy
/// of its forwarded ports.
///
/// The base fields are fixed for a running generation (a restart applies changes); `blocklists`
/// apply to running connections at once (an overlay that only adds deny entries). Evaluation order:
/// `crates/instance/src/policy.rs`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[ts(export)]
pub struct SecurityProfile {
    pub id: SecurityProfileId,
    #[serde(flatten)]
    pub meta: EntityMeta,
    pub name: String,
    /// Private/VPN-internal ranges that may be reached *through the tunnel*. Must lie inside the
    /// profile's allowed IPs. Loopback, link-local and multicast are never allowed.
    #[ts(type = "Array<string>")]
    pub allow_private: Vec<IpNetwork>,
    /// Destination ports refused for payload flows.
    pub blocked_ports: Vec<u16>,
    /// Firewall allow rule: when not empty, payload may reach only these networks (default
    /// deny); a private one still needs `allow_private`. Never opens loopback, link-local,
    /// multicast, the host or another connection.
    #[serde(default)]
    #[ts(type = "Array<string>")]
    pub allowed_destinations: Vec<IpNetwork>,
    /// Firewall allow rule: when not empty, payload may use only these destination ports.
    #[serde(default)]
    pub allowed_ports: Vec<PortRange>,
    /// IP blocklists, denied as destinations and as inbound sources.
    pub blocklists: Vec<BlocklistId>,
    pub auto_ban: AutoBanSettings,
}

