/// One upstream resolver; every transport is carried by the Instance's tunnel.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(tag = "transport", rename_all = "snake_case")]
#[ts(export)]
pub enum DnsServer {
    /// Plain DNS over UDP, retried over TCP on truncation.
    Udp {
        #[ts(type = "string")]
        address: SocketAddr,
    },
    Tcp {
        #[ts(type = "string")]
        address: SocketAddr,
    },
    /// DNS over TLS (RFC 7858). `address` is the numeric bootstrap IP; the certificate is
    /// verified against `server_name`.
    Tls {
        #[ts(type = "string")]
        address: SocketAddr,
        server_name: String,
    },
    /// DNS over HTTPS (RFC 8484). `url` must be `https://`; `address` is the numeric bootstrap IP.
    Https {
        #[ts(type = "string")]
        address: SocketAddr,
        url: String,
    },
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, TS)]
#[ts(export)]
