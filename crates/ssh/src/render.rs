//! The generated `~/.ssh/vpn-manager.conf`. Every value comes from validated entity fields; the
//! output is deterministic (sorted by alias), so "is this still exactly what we wrote" is a plain
//! comparison.

use std::fmt::Write as _;
use std::path::Path;

use vpn_domain::{SshExistingHost, SshHost, SshHostKind, Text, tr};

pub const HEADER: &str = "# Generated by VPN Manager. Edit these hosts in the VPN Manager app.\n\
# If this file is changed by hand, VPN Manager stops writing it until you resolve that in the app.\n";

/// Unix socket paths are limited to 104 bytes on macOS (108 on Linux), terminator included.
const SUN_PATH_MAX: usize = 104;
/// ssh first binds a master socket at `<ControlPath>.<16 random characters>`.
const MUX_TEMP_SUFFIX: usize = 17;
/// `%C` expands to a SHA-1 hex digest.
const CONNECTION_HASH: usize = 40;

fn bare_safe(s: &str) -> bool {
    s.chars()
        .all(|c| c.is_ascii_alphanumeric() || matches!(c, '/' | '.' | '_' | '-' | '+' | '@'))
}

/// A path for a `ProxyCommand` line. ssh expands `%` tokens in it and runs the line with the
/// user's shell (sh, zsh, fish, csh...): a plainly safe path is written bare, anything else
/// single-quoted. What single quotes do not protect the same way in all of them (`'`, `\`, `!`),
/// `%` (an ssh token) and control characters are refused. `what` names the file.
fn shell_word(path: &Path, what: &Text) -> Result<String, Text> {
    let s = path.to_str().ok_or_else(|| {
        tr!(
            "The path of {what} is not UTF-8",
            "{what}的路徑不是 UTF-8",
            "{what}のパスが UTF-8 ではありません";
            what = what.clone()
        )
    })?;
    if !path.is_absolute() {
        return Err(tr!(
            "The path of {what} must be absolute: {s}",
            "{what}的路徑必須是絕對路徑：{s}",
            "{what}のパスは絶対パスにしてください：{s}";
            what = what.clone()
        ));
    }
    if s.chars()
        .any(|c| c.is_control() || matches!(c, '\'' | '\\' | '!' | '%'))
    {
        return Err(tr!(
            "The path of {what} has a character that cannot be written safely into the ssh configuration: {s}",
            "{what}的路徑含有無法安全寫入 ssh 設定的字元：{s}",
            "{what}のパスに、ssh の設定に安全に書き込めない文字が含まれています：{s}";
            what = what.clone()
        ));
    }
    Ok(if bare_safe(s) {
        s.to_string()
    } else {
        format!("'{s}'")
    })
}

/// How VPN-routed hosts are written.
///
/// That is `vpnctl ssh-proxy` with the installation's Gateway key, and a connection-sharing path of their own, so an ssh master opened another way (directly,
/// before the host was routed) is never reused for them.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Routing {
    binary: String,
    key_file: String,
    /// `ControlPath` directory as written, or `None` when a socket there could exceed the
    /// platform limit (sharing is then turned off for these hosts).
    control_dir: Option<String>,
}

impl Routing {
    /// `ssh_dir`: the SSH directory as written in the file (e.g. `~/.ssh`) and its real path.
    ///
    /// # Errors
    ///
    /// A user-facing reason when the `vpnctl` binary or key file path is not absolute UTF-8
    /// or holds a character that cannot be written safely into the ssh config.
    pub fn new(
        binary: &Path,
        key_file: &Path,
        ssh_dir: &str,
        ssh_dir_real: &Path,
    ) -> Result<Self, Text> {
        let socket_len = ssh_dir_real.as_os_str().len()
            + "/vpnm-65535-".len()
            + CONNECTION_HASH
            + MUX_TEMP_SUFFIX;
        let control_dir = (socket_len < SUN_PATH_MAX && bare_safe(ssh_dir.trim_start_matches('~')))
            .then(|| ssh_dir.to_string());
        Ok(Self {
            binary: shell_word(binary, &tr!("vpnctl", "vpnctl ", "vpnctl "))?,
            key_file: shell_word(
                key_file,
                &tr!(
                    "the Gateway key file",
                    "代理埠金鑰檔",
                    "ゲートウェイの鍵ファイル"
                ),
            )?,
            control_dir,
        })
    }

    /// The `ProxyCommand` value for the Gateway on `port` (a number, or `{port}` for a preview).
    pub fn proxy_command(&self, port: impl std::fmt::Display) -> String {
        format!(
            "{} ssh-proxy --gateway 127.0.0.1:{port} --key-file {} %h %p",
            self.binary, self.key_file
        )
    }

    /// The `ControlPath` value for the Gateway on `port`.
    pub fn control_path(&self, port: impl std::fmt::Display) -> String {
        self.control_dir
            .as_ref()
            .map_or_else(|| "none".into(), |dir| format!("{dir}/vpnm-{port}-%C"))
    }
}

/// A host pattern that can be written back unquoted and matches exactly one name.
fn plain_pattern(p: &str) -> bool {
    !p.is_empty()
        && p.chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '_' | '-' | ':' | '[' | ']'))
}

/// One host to render.
pub struct Entry<'a> {
    pub host: &'a SshHost,
    /// Every name the block is written for.
    pub patterns: Vec<String>,
    /// The port of its Gateway, if it uses one.
    pub gateway_port: Option<u16>,
}

impl<'a> Entry<'a> {
    /// `block`: for an overlay, the user's host block it applies to. All of the block's plain
    /// names are covered, so `ssh` by any of them goes the same way.
    #[must_use]
    pub fn new(
        host: &'a SshHost,
        gateway_port: Option<u16>,
        block: Option<&SshExistingHost>,
    ) -> Self {
        let mut patterns = vec![host.alias.clone()];
        if host.kind == SshHostKind::Overlay
            && let Some(b) = block
        {
            for p in &b.patterns {
                if plain_pattern(p) && !patterns.contains(p) {
                    patterns.push(p.clone());
                }
            }
        }
        Self {
            host,
            patterns,
            gateway_port,
        }
    }
}

/// Render the file. An entry that wants a Gateway without a known port or routing is an error:
/// written without its `ProxyCommand` it would connect directly.
///
/// # Errors
///
/// A user-facing reason naming the first such entry.
pub fn render(entries: &[Entry<'_>], routing: Option<&Routing>) -> Result<String, Text> {
    let mut sorted: Vec<&Entry<'_>> = entries.iter().collect();
    sorted.sort_by(|a, b| a.host.alias.cmp(&b.host.alias));
    let mut out = String::from(HEADER);
    for e in sorted {
        let h = e.host;
        let _ = write!(out, "\nHost {}\n", e.patterns.join(" "));
        if h.kind == SshHostKind::Host {
            if let Some(v) = &h.host_name {
                let _ = writeln!(out, "  HostName {v}");
            }
            if let Some(v) = &h.user {
                let _ = writeln!(out, "  User {v}");
            }
            if let Some(v) = h.port {
                let _ = writeln!(out, "  Port {v}");
            }
            if let Some(v) = &h.identity_file {
                let _ = writeln!(out, "  IdentityFile {v}");
                if h.identities_only {
                    out.push_str("  IdentitiesOnly yes\n");
                }
            }
        }
        if h.gateway_id.is_some() {
            let (Some(r), Some(port)) = (routing, e.gateway_port) else {
                let alias = &h.alias;
                return Err(tr!(
                    "“{alias}” must connect through a Gateway, but no ProxyCommand can be made for it",
                    "「{alias}」需要經代理埠連線，但無法產生 ProxyCommand",
                    "「{alias}」はゲートウェイ経由で接続する必要がありますが、ProxyCommand を生成できません"
                ));
            };
            let _ = writeln!(out, "  ProxyCommand {}", r.proxy_command(port));
            let _ = writeln!(out, "  ControlPath {}", r.control_path(port));
        }
        if let Some(v) = h.server_alive_interval {
            let _ = writeln!(out, "  ServerAliveInterval {v}");
        }
    }
    Ok(out)
}

/// SHA-256 of the text, hex (identifies what was last written).
#[must_use]
pub fn digest(text: &str) -> String {
    use sha2::{Digest, Sha256};
    hex::encode(Sha256::digest(text.as_bytes()))
}

#[cfg(test)]
mod tests {
    use std::str::FromStr;

    use vpn_domain::{EntityMeta, GatewayId, SshHostId, Timestamp};

    use super::*;

    fn host(alias: &str, kind: SshHostKind, gateway: bool) -> SshHost {
        SshHost {
            id: SshHostId::new(),
            meta: EntityMeta {
                revision: 1,
                created_at: Timestamp::now(),
                updated_at: Timestamp::now(),
            },
            kind,
            alias: alias.into(),
            host_name: (kind == SshHostKind::Host).then(|| "example.com".into()),
            user: (kind == SshHostKind::Host).then(|| "deploy".into()),
            port: (kind == SshHostKind::Host).then_some(2222),
            identity_file: (kind == SshHostKind::Host).then(|| "~/.ssh/id_ed25519".into()),
            identities_only: kind == SshHostKind::Host,
            gateway_id: gateway
                .then(|| GatewayId::from_str("6f1c4a9e-2c1b-4c5e-9a40-0b7f1c2d3e4f").unwrap()),
            server_alive_interval: gateway.then_some(60),
        }
    }

    fn routing() -> Routing {
        Routing::new(
            Path::new("/opt/vpn/vpnctl"),
            Path::new("/var/lib/vpn/gateway.key"),
            "~/.ssh",
            Path::new("/home/me/.ssh"),
        )
        .unwrap()
    }

    #[test]
    fn quotes_paths_with_spaces_and_refuses_what_quotes_cannot_hold() {
        let r = Routing::new(
            Path::new("/Applications/VPN Manager.app/Contents/MacOS/vpnctl"),
            Path::new("/Users/me/Library/Application Support/VPN Manager/state/gateway.key"),
            "~/.ssh",
            Path::new("/Users/me/.ssh"),
        )
        .unwrap();
        assert_eq!(
            r.proxy_command(1080),
            "'/Applications/VPN Manager.app/Contents/MacOS/vpnctl' ssh-proxy --gateway 127.0.0.1:1080 \
             --key-file '/Users/me/Library/Application Support/VPN Manager/state/gateway.key' %h %p"
        );
        // ssh splits the line the way a shell would: the quoted paths stay single words.
        let (_, args) =
            crate::config::tokenize(&format!("ProxyCommand {}", r.proxy_command(1080))).unwrap();
        assert_eq!(
            args[0],
            "/Applications/VPN Manager.app/Contents/MacOS/vpnctl"
        );
        for bad in [
            "relative/vpnctl",
            "/opt/it's/vpnctl",
            "/opt/100%/vpnctl",
            "/opt/a\\b/vpnctl",
            "/opt/x\n/vpnctl",
        ] {
            assert!(
                Routing::new(
                    Path::new(bad),
                    Path::new("/k"),
                    "~/.ssh",
                    Path::new("/h/.ssh")
                )
                .is_err(),
                "{bad}"
            );
        }
    }

    #[test]
    fn never_renders_a_gateway_host_without_its_proxy() {
        let a = host("work", SshHostKind::Host, true);
        assert!(render(&[Entry::new(&a, None, None)], Some(&routing())).is_err());
        assert!(render(&[Entry::new(&a, Some(1080), None)], None).is_err());
    }
}
