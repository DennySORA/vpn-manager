/** 「A、B與C」, with a space where 與 meets a Latin word (「SSH 下載與 App 沙箱」). */
function joinZh(parts: readonly string[]): string {
  if (parts.length < 2) return parts[0] ?? "";
  const last = parts[parts.length - 1] ?? "";
  const head = parts.slice(0, -1).join("、");
  const before = /[A-Za-z0-9]$/.test(head) ? " " : "";
  const after = /^[A-Za-z0-9]/.test(last) ? " " : "";
  return `${head}${before}與${after}${last}`;
}

